import Providers from '@/components/Providers';
import PWARegister from '@/components/PWARegister';
import { Toaster } from '@/components/ui/sonner';
import { getLocale } from '@/lib/i18n/getDictionary';
import type { Metadata } from 'next';
import { ThemeProvider } from 'next-themes';
import { Noto_Sans_Bengali, Outfit, Ovo } from 'next/font/google';
import './globals.css';

const outfit = Outfit({
  subsets: ['latin'],
  variable: '--font-outfit',
  weight: ['400', '500', '600', '700'],
});

const ovo = Ovo({
  subsets: ['latin'],
  variable: '--font-ovo',
  weight: ['400'],
});

// Outfit/Ovo only cover Latin script; Bangla text falls back to this font
// (wired in as a fallback in globals.css) so it renders with proper glyphs
// instead of the browser's default serif fallback.
const notoSansBengali = Noto_Sans_Bengali({
  subsets: ['bengali'],
  variable: '--font-bengali',
  weight: ['400', '500', '600', '700'],
});

export const metadata: Metadata = {
  title: 'Sebagriho',
  description: 'Generated by sebagriho development team',
  applicationName: 'Sebagriho',
  appleWebApp: {
    capable: true,
    statusBarStyle: 'default',
    title: 'Sebagriho',
  },
  formatDetection: {
    telephone: false,
  },
};

export default async function RootLayout({ children }: LayoutProps<'/'>) {
  const locale = await getLocale();

  return (
    <html
      lang={locale}
      suppressHydrationWarning
      className={`${outfit.variable} ${ovo.variable} ${notoSansBengali.variable} h-full antialiased`}
    >
      <body className='flex min-h-full flex-col' suppressHydrationWarning>
        <ThemeProvider
          attribute='class'
          defaultTheme='system'
          enableSystem
          disableTransitionOnChange
        >
          <Providers locale={locale}>
            <PWARegister />
            {children}
            <Toaster />
          </Providers>
        </ThemeProvider>
      </body>
    </html>
  );
}
